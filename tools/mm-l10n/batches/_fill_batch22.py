def pcs(s): return sorted(re.findall(r"%[sSdD]\d*(?:_[A-Za-z]+)?", s))
def brk(s):
    from collections import Counter
    return Counter(re.findall(r"\[[^\[\]]*\]", s))

with open(SRC, encoding="utf-8") as f:
    lines=f.read().split("\n")
header=lines[0]; out=[header]
missing=[]; pcerr=[]; brkerr=[]
for ln in lines[1:]:
    if ln=="":
        out.append(ln); continue
    parts=ln.split("\t")
    if len(parts)!=4:
        pcerr.append(("BADCOLS",ln[:40])); out.append(ln); continue
    f_,k,eng,_=parts
    if k not in T:
        missing.append(k); out.append(ln); continue
    zh=T[k]
    if pcs(eng)!=pcs(zh): pcerr.append((k,pcs(eng),pcs(zh)))
    be,bz=brk(eng),brk(zh)
    if be!=bz:
        brkerr.append((k,"extra_zh="+str(dict(bz-be)),"miss_zh="+str(dict(be-bz))))
    out.append("\t".join([f_,k,eng,zh]))
with open(SRC,"w",encoding="utf-8") as f:
    f.write("\n".join(out))
